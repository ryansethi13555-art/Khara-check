/**
 * Shared types. Everything that ends up in an evidence bundle is described here,
 * so that `khara-check report` and `khara-check verify` can re-read a bundle without a browser.
 */

export type CanaryType = 'search-term' | 'email' | 'phone' | 'text';

/** A planted test value: something typed into the site that we then look for on the wire. */
export interface Canary {
  /** Name used in the journey file, e.g. `{{search}}`. */
  name: string;
  type: CanaryType;
  /** Plain-language label used in reports, e.g. "search term". */
  label: string;
  /** The exact text that is typed into the site. */
  value: string;
  /** True when the value carries a random marker that exists nowhere else. */
  unique: boolean;
  /** The random marker itself, when there is one. */
  marker?: string;
  /** Country calling code for phone canaries, digits only (default "91"). */
  countryCode?: string;
  /** How the value came to be: generated by Khara Check, or supplied by the person running it. */
  origin: 'generated' | 'supplied';
}

export interface StepRecord {
  index: number;
  action: string;
  label: string;
  startedAt: number;
  endedAt: number;
  pageUrl: string;
  ok: boolean;
  /** Who acted: Khara Check, or a person (attach mode, or a handoff during an automated run). */
  actor?: 'khara-check' | 'person';
  error?: string;
  artifact?: string;
}

export interface PostData {
  encoding: 'utf8' | 'base64';
  text: string;
  bytes: number;
  sha256: string;
}

export interface Initiator {
  type: string;
  url?: string;
  lineNumber?: number;
  columnNumber?: number;
  /** Script URLs on the JavaScript call stack, innermost first, de-duplicated. */
  stack?: string[];
}

export interface ResponseRecord {
  status: number;
  statusText: string;
  headers: Record<string, string>;
  mimeType?: string;
  remoteAddress?: string;
  protocol?: string;
  setCookies?: string[];
}

export type SandboxDisposition = 'answered-locally' | 'passed-to-local-site';

export interface RequestRecord {
  /** Stable id inside the bundle, e.g. "r0007". */
  id: string;
  seq: number;
  kind: 'http' | 'websocket';
  /** Where this record came from. "cdp" is the browser's own network log. */
  source: 'cdp' | 'playwright' | 'sandbox' | 'har';
  method: string;
  url: string;
  resourceType: string;
  /** Milliseconds since the Unix epoch, from the browser's clock. */
  wallTime: number;
  documentUrl?: string;
  frameId?: string;
  pageIndex: number;
  requestHeaders: Record<string, string>;
  /** "wire" when the headers are the ones the browser actually sent. */
  headersSource: 'wire' | 'provisional';
  postData?: PostData;
  initiator?: Initiator;
  redirectedFrom?: string;
  response?: ResponseRecord;
  failure?: string;
  /** Present only in sandbox runs. */
  sandbox?: SandboxDisposition;
  /** WebSocket frames sent by the page (kind === "websocket"). */
  framesSent?: { wallTime: number; postData: PostData }[];
  /** Index of the journey step that was running when the request started (-1: before the first step). */
  step: number;
}

export interface RunInfo {
  tool: { name: string; version: string };
  journeyName: string;
  site: { name: string; origin: string; firstPartyDomains: string[] };
  mode: 'sandbox' | 'live';
  /**
   * "automated": Khara Check drove the browser. "attached": a person browsed and Khara Check only listened.
   * "imported": a person recorded the traffic in their own browser's DevTools and Khara Check read the HAR file.
   */
  capture: 'automated' | 'attached' | 'imported';
  /** How the consent banner was answered in this run, when the journey describes one. */
  consent?: 'no-choice' | 'reject' | 'accept';
  startedAt: number;
  endedAt: number;
  seed?: string;
  environment: {
    node: string;
    platform: string;
    playwright: string;
    browser: string;
    browserVersion: string;
    userAgent: string;
    viewport: { width: number; height: number };
    locale: string;
    timezone: string;
    headless: boolean;
  };
  steps: StepRecord[];
  /** Moments a person took over the browser during an automated run (bot checks, OTPs, logins). */
  handoffs?: StepRecord[];
  notes: string[];
  /**
   * DNS aliases (CNAME chains) of the site's own hostnames, looked up when the capture was made.
   * A hostname that looks like the site's own but is an alias for another company's server is
   * counted as that company.
   */
  dns?: Record<string, string[]>;
}

/** One place inside one request where a canary was found. */
export interface Sighting {
  canary: string;
  formId: string;
  formKind: 'plain' | 'encoded' | 'hash';
  formLabel: string;
  /** "full" when the whole value was found, "marker" when only the unique marker was. */
  exactness: 'full' | 'marker';
  surface: 'url' | 'header' | 'body' | 'websocket';
  /** Header name, for header sightings. */
  surfaceName?: string;
  /** Decoding steps from the raw surface down to the text that held the value. */
  chain: string[];
  /** Short machine-readable field path, e.g. `cd[search_string]` or `evtData.term`. */
  field: string;
  /** Offset of the match inside the decoded text at the end of the chain. */
  offset: number;
  length: number;
  /** Offset inside the raw surface text, when the value is literally present there. */
  rawOffset?: number;
  /** A short excerpt of the decoded text around the match, for humans. */
  excerpt: string;
  /** Start and end of the match inside `excerpt`. */
  excerptAt: [number, number];
  /** What this field is for, in plain words, when a decoder knows. */
  meaning?: string;
}

export interface DecodedField {
  name: string;
  value: string;
  meaning?: string;
}

export interface DecodedCall {
  decoder: string;
  vendor: string;
  product: string;
  category: VendorCategory;
  /** What kind of call this is, in plain words. */
  purpose: string;
  eventName?: string;
  accountId?: string;
  fields: DecodedField[];
  /** Browser or user identifiers that travel in the same request. */
  identifiers: DecodedField[];
}

export type VendorCategory =
  | 'advertising'
  | 'analytics'
  | 'session-replay'
  | 'customer-engagement'
  | 'attribution'
  | 'tag-manager'
  | 'other';

export interface Recipient {
  host: string;
  /** Registrable domain (eTLD+1), e.g. facebook.com. */
  domain: string;
  party: 'first' | 'third';
  vendor?: string;
  product?: string;
  category?: VendorCategory;
  /** The other company's server that a site-looking hostname is an alias for (from run.dns). */
  aliasOf?: string;
  /**
   * For a request to the site's own address that has the shape of a known data collection
   * service (for example a RudderStack or server-side Google Tag Manager endpoint): that service.
   * The browser cannot see where such a collector sends the data next.
   */
  collector?: { vendor: string; product: string };
}

export interface Finding {
  id: string;
  canary: string;
  recipient: Recipient;
  requestId: string;
  requestSeq: number;
  method: string;
  wallTime: number;
  step: number;
  /** Milliseconds between the start of the step and this request. */
  msAfterStep: number;
  sightings: Sighting[];
  /** The strongest way the value appeared: readable text beats encoded beats hashed. */
  strongest: 'plain' | 'encoded' | 'hash';
  decoded?: DecodedCall;
  initiator?: Initiator;
  delivery: 'delivered' | 'attempted' | 'sandboxed';
  responseStatus?: number;
  remoteAddress?: string;
  /** "unique": the value carried a run-unique marker. "common": it did not. */
  confidence: 'unique' | 'common';
  /** The consent state when the request left: before any choice, after "reject", after "accept". */
  consent?: 'before-choice' | 'after-reject' | 'after-accept';
}

export interface ContactedParty {
  recipient: Recipient;
  requests: number;
  firstRequestId: string;
  receivedCanary: boolean;
}

export interface Analysis {
  schema: 1;
  canaries: Canary[];
  /** Third-party findings: the planted value left the site. */
  leaks: Finding[];
  /** First-party findings: the value went to the site's own servers. Expected, listed for completeness. */
  firstParty: Finding[];
  /** Every third party contacted during the run, whether or not it received a canary. */
  contacted: ContactedParty[];
  totals: {
    requests: number;
    thirdPartyRequests: number;
    thirdPartyDomains: number;
    leakingRecipients: number;
  };
}
